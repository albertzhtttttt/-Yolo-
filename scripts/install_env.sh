#!/bin/bash
# =============================================================================
# 服务器环境安装脚本
# 适用于：Ubuntu 22.04.5 LTS，CUDA 12.1，Python 3.10+
# 执行方式：bash scripts/install_env.sh
# =============================================================================

set -e  # 任意命令失败则退出

echo "========================================"
echo "  红树林林窗探测项目 - 环境安装脚本"
echo "========================================"

# --------------------------------------------------------------------------
# 1. 更新 pip
# --------------------------------------------------------------------------
echo "[1/7] 升级 pip..."
pip install --upgrade pip

# --------------------------------------------------------------------------
# 2. 安装 PyTorch（已由服务器预装 CUDA 12.1 版本，跳过；若未安装则取消注释）
# --------------------------------------------------------------------------
# echo "[2/7] 安装 PyTorch 2.3.1+cu121..."
# pip install torch==2.3.1+cu121 torchvision==0.18.1+cu121 \
#     --index-url https://download.pytorch.org/whl/cu121

echo "[2/7] 跳过 PyTorch（假设服务器已预装 2.3.1+cu121）"

# --------------------------------------------------------------------------
# 3. 安装 Ultralytics YOLOv8
# --------------------------------------------------------------------------
echo "[3/7] 安装 Ultralytics YOLOv8..."
pip install ultralytics==8.2.87

# --------------------------------------------------------------------------
# 4. 安装 YOLOv5（对比实验用）
# --------------------------------------------------------------------------
echo "[4/7] 安装 YOLOv5 依赖..."
pip install "gitpython>=3.1.30" "setuptools>=65.5.1"
# YOLOv5 通过 torch.hub 加载，无需独立安装包

# --------------------------------------------------------------------------
# 5. 安装图像处理与数值计算库
# --------------------------------------------------------------------------
echo "[5/7] 安装图像处理库..."
pip install \
    opencv-python==4.12.0.88 \
    numpy==1.24.4 \
    Pillow==10.4.0 \
    scipy==1.13.1 \
    scikit-image==0.24.0 \
    albumentations==1.4.20

# --------------------------------------------------------------------------
# 6. 安装地理信息处理库（用于 GeoTIFF 预测输出 KML/SHP，方案A）
# --------------------------------------------------------------------------
echo "[6/7] 安装地理信息处理库..."
pip install \
    rasterio==1.3.11 \
    pyproj==3.6.1 \
    simplekml==1.3.6 \
    pyshp==2.3.1 \
    shapely==2.0.6

# --------------------------------------------------------------------------
# 7. 安装可视化与数据分析库
# --------------------------------------------------------------------------
echo "[7/7] 安装可视化与分析库..."
pip install \
    matplotlib==3.9.2 \
    seaborn==0.13.2 \
    pandas==2.2.3 \
    PyYAML==6.0.2 \
    tqdm==4.66.5 \
    thop==0.1.1.post2209072238   # 用于计算模型 FLOPs/Params

echo ""
echo "========================================"
echo "  安装完成！验证关键依赖..."
echo "========================================"
python -c "
import torch, ultralytics, cv2, numpy, rasterio, simplekml, shapefile
import matplotlib, seaborn, pandas
print(f'  torch:        {torch.__version__}')
print(f'  ultralytics:  {ultralytics.__version__}')
print(f'  opencv:       {cv2.__version__}')
print(f'  numpy:        {numpy.__version__}')
print(f'  rasterio:     {rasterio.__version__}')
print(f'  CUDA 可用:    {torch.cuda.is_available()}')
if torch.cuda.is_available():
    print(f'  GPU:          {torch.cuda.get_device_name(0)}')
    print(f'  显存:         {torch.cuda.get_device_properties(0).total_memory / 1024**3:.1f} GB')
print('  所有依赖验证通过！')
"
